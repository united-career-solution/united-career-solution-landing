/**
 * Generate map data with adjusted proportions: USA larger, UK smaller.
 * Run: node scripts/generate-map-data.mjs
 */

const STATES_URL = "https://cdn.jsdelivr.net/npm/us-atlas@3/states-10m.json";
const COUNTRY_URL = "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json";
const fs = await import("fs");

function simplifyRing(points, tolerance) {
  if (points.length <= 2) return points;
  let maxDist = 0, maxIdx = 0;
  const start = points[0], end = points[points.length - 1];
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDist(points[i], start, end);
    if (d > maxDist) { maxDist = d; maxIdx = i; }
  }
  if (maxDist > tolerance) {
    const left = simplifyRing(points.slice(0, maxIdx + 1), tolerance);
    const right = simplifyRing(points.slice(maxIdx), tolerance);
    return [...left.slice(0, -1), ...right];
  }
  return [start, end];
}
function perpDist(p, a, b) {
  const dx=b[0]-a[0],dy=b[1]-a[1],l=dx*dx+dy*dy;
  if(!l) return Math.hypot(p[0]-a[0],p[1]-a[1]);
  const t=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/l));
  return Math.hypot(p[0]-(a[0]+t*dx),p[1]-(a[1]+t*dy));
}
function decodeArc(i,arcs,x){const r=i<0,idx=r?~i:i,a=arcs[idx],c=[];let px=0,py=0;for(const[dx,dy]of a){px+=dx;py+=dy;c.push([px*x.scale[0]+x.translate[0],py*x.scale[1]+x.translate[1]])}if(r)c.reverse();return c}
function decodeRing(ring,arcs,x){const c=[];for(const i of ring){const a=decodeArc(i,arcs,x);c.push(...(c.length?a.slice(1):a))}return c}
function getRings(g,arcs,x){if(g.type==="Polygon")return g.arcs.map(r=>decodeRing(r,arcs,x));if(g.type==="MultiPolygon")return g.arcs.flatMap(p=>p.map(r=>decodeRing(r,arcs,x)));return[]}
function project(rings,b,t){const lr=b.maxLon-b.minLon,la=b.maxLat-b.minLat,s=Math.min(t.w/lr,t.h/la),ox=t.x+(t.w-lr*s)/2,oy=t.y+(t.h-la*s)/2;return rings.map(r=>r.map(([lo,la2])=>[(lo-b.minLon)*s+ox,(b.maxLat-la2)*s+oy]))}
function toPath(p,tol=0){return p.map(r=>{let pts=r;if(tol>0&&pts.length>4)pts=simplifyRing(pts,tol);if(pts.length<3)return"";return pts.map((pt,i)=>{const x=Math.round(pt[0]*10)/10,y=Math.round(pt[1]*10)/10;return i===0?`M${x},${y}`:`L${x},${y}`}).join(" ")+" Z"}).filter(p=>p).join(" ")}

async function main() {
  console.log("Fetching data...");
  const [stR, cR] = await Promise.all([fetch(STATES_URL), fetch(COUNTRY_URL)]);
  const st = await stR.json(), ct = await cR.json();

  // === USA: larger projection area ===
  const CONT = { minLon:-125, maxLon:-66.5, minLat:24, maxLat:50 };
  const USA_T = { x: 0, y: 6, w: 60, h: 70 };  // was w:58,h:66 — now bigger
  const SKIP = new Set(["02","15","60","66","69","72","78"]);
  const paths = [];
  for (const g of st.objects.states.geometries) {
    if (SKIP.has(g.id)) continue;
    const rings = getRings(g,st.arcs,st.transform);
    if (!rings.length) continue;
    const sig = rings.filter(r=>{let a=Infinity,b=-Infinity,c=Infinity,d=-Infinity;for(const[x,y]of r){a=Math.min(a,x);b=Math.max(b,x);c=Math.min(c,y);d=Math.max(d,y)}return(b-a)>0.15||(d-c)>0.15});
    if (!sig.length) continue;
    const p = toPath(project(sig,CONT,USA_T),0.15);
    if (p) paths.push(p);
  }

  // === UK: smaller projection area ===
  const UKB = { minLon:-7.573, maxLon:1.683, minLat:49.96, maxLat:58.634 };
  const UK_T = { x: 67, y: 16, w: 24, h: 48 };  // was x:63,w:28,h:60 — now smaller

  let ukMain="", ukIre="";
  for (const g of ct.objects.countries.geometries) {
    if (g.id==="826") {
      const rings = getRings(g,ct.arcs,ct.transform);
      const proj = project(rings,UKB,UK_T);
      const pp = proj.map(r=>{if(r.length<3)return"";return r.map((pt,i)=>{const x=Math.round(pt[0]*10)/10,y=Math.round(pt[1]*10)/10;return i===0?`M${x},${y}`:`L${x},${y}`}).join(" ")+" Z"}).filter(p=>p);
      if(pp.length>=2){ukIre=pp[0];ukMain=pp[1]}else if(pp.length===1)ukMain=pp[0];
    }
  }

  // UK region borders
  function projUK([lon,lat]){const lr=UKB.maxLon-UKB.minLon,la=UKB.maxLat-UKB.minLat,s=Math.min(UK_T.w/lr,UK_T.h/la),ox=UK_T.x+(UK_T.w-lr*s)/2,oy=UK_T.y+(UK_T.h-la*s)/2;return[Math.round(((lon-UKB.minLon)*s+ox)*10)/10,Math.round(((UKB.maxLat-lat)*s+oy)*10)/10]}
  const ukRegions = [
    [[-3.4,55.0],[-2.8,55.6],[-2.0,55.8]],
    [[-3.1,51.4],[-3.0,51.8],[-3.1,52.3],[-3.0,52.8],[-2.9,53.2]],
    [[-6.3,54.4],[-5.5,54.2],[-6.0,54.0]],
  ].map(l=>l.map(projUK).map((pt,i)=>i===0?`M${pt[0]},${pt[1]}`:`L${pt[0]},${pt[1]}`).join(" ")).join(" ");

  const all = paths.join(" ");
  fs.writeFileSync("components/hero/mapPaths.js",
`// Auto-generated — DO NOT EDIT
// viewBox: 0 0 100 80 | USA larger, UK smaller, no Alaska
// Generated by: scripts/generate-map-data.mjs

export const US_STATES_PATH = \`${all}\`;
export const UK_MAIN_PATH = \`${ukMain}\`;
export const UK_IRELAND_PATH = \`${ukIre}\`;
export const UK_REGIONS_PATH = \`${ukRegions}\`;
`,"utf-8");

  console.log(`States: ${all.length} chars (${paths.length}), UK main: ${ukMain.length}, UK Ire: ${ukIre.length}, UK regions: ${ukRegions.length}`);

  // City positions
  const s=Math.min(USA_T.w/(CONT.maxLon-CONT.minLon),USA_T.h/(CONT.maxLat-CONT.minLat));
  const ox=USA_T.x+(USA_T.w-(CONT.maxLon-CONT.minLon)*s)/2, oy=USA_T.y+(USA_T.h-(CONT.maxLat-CONT.minLat)*s)/2;
  const cities={"New York":[-74.006,40.7128],"Los Angeles":[-118.2437,34.0522],"Houston":[-95.3698,29.7604],"Chicago":[-87.6298,41.8781]};
  console.log("\n=== US CITIES ===");
  for(const[c,[lon,lat]]of Object.entries(cities)){const px=(lon-CONT.minLon)*s+ox,py=(CONT.maxLat-lat)*s+oy;console.log(`${c}: x=${px.toFixed(1)}, y%=${(py/80*100).toFixed(1)}%`)}
  const us=Math.min(UK_T.w/(UKB.maxLon-UKB.minLon),UK_T.h/(UKB.maxLat-UKB.minLat));
  const uox=UK_T.x+(UK_T.w-(UKB.maxLon-UKB.minLon)*us)/2,uoy=UK_T.y+(UK_T.h-(UKB.maxLat-UKB.minLat)*us)/2;
  const ukC={"London":[-0.1276,51.5074],"Manchester":[-2.2426,53.4808]};
  console.log("=== UK CITIES ===");
  for(const[c,[lon,lat]]of Object.entries(ukC)){const px=(lon-UKB.minLon)*us+uox,py=(UKB.maxLat-lat)*us+uoy;console.log(`${c}: x=${px.toFixed(1)}, y%=${(py/80*100).toFixed(1)}%`)}
}
main().catch(console.error);
